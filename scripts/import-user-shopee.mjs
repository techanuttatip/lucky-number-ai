function extractCleanNumbers(text) {
  const numberRegex = /(0[689]\d{8}|0[689]\d{1}[-\s]\d{3}[-\s]\d{4}|0[689]\d{2}[-\s]\d{3}[-\s]\d{4}|0[689]\d{1}[-\s]\d{7})/g;
  const matches = text.match(numberRegex) || [];
  const unique = new Set();
  for (const m of matches) {
    const clean = m.replace(/\D/g, "");
    if (clean.length === 10 && (clean.startsWith("06") || clean.startsWith("08") || clean.startsWith("09"))) {
      unique.add(clean);
    }
  }
  return Array.from(unique);
}

// Simple rule scoring for node script
function calculateNumerology(raw) {
  const digits = raw.split("").map((d) => parseInt(d, 10));
  const sum = digits.reduce((a, b) => a + b, 0);

  // Formatted
  const formatted = `${raw.slice(0, 3)}-${raw.slice(3, 6)}-${raw.slice(6)}`;

  // Provider
  let provider = "AIS";
  if (raw.startsWith("091") || raw.startsWith("093") || raw.startsWith("097") || raw.startsWith("063") || raw.startsWith("086")) {
    provider = "TRUE";
  } else if (raw.startsWith("061") || raw.startsWith("062") || raw.startsWith("065") || raw.startsWith("080") || raw.startsWith("081") || raw.startsWith("082") || raw.startsWith("098") || raw.startsWith("095") || raw.startsWith("092")) {
    provider = "AIS";
  }

  // Decomposed pairs in last 7
  const last7 = raw.slice(-7);
  const pairs = [];
  for (let i = 0; i < last7.length - 1; i++) {
    pairs.push(last7.slice(i, i + 2));
  }

  // Dangerous pairs
  const dangerousList = ["00", "01", "10", "02", "20", "03", "30", "07", "70", "08", "80", "13", "31", "17", "71", "18", "81", "27", "72", "37", "73", "48", "84", "58", "85", "67", "76", "77", "88"];
  const dangerousFound = pairs.filter((p) => dangerousList.includes(p));

  // Auspicious pairs (Grade S & A)
  const auspiciousList = ["78", "87", "89", "98", "79", "97", "28", "82", "63", "36", "39", "93", "24", "42", "45", "54", "56", "65", "59", "95", "99", "66", "55", "44", "15", "51", "14", "41", "16", "61", "19", "91", "23", "32", "26", "62", "29", "92", "35", "53", "46", "64", "49", "94", "69", "96", "52", "25", "74", "47", "86", "68"];
  const auspiciousFound = pairs.filter((p) => auspiciousList.includes(p));

  let score = 50;
  score += (auspiciousFound.length * 9);
  score -= (dangerousFound.length * 25);

  // Good sum bonus (41, 42, 45, 50, 51, 54, 55, 56, 59, 63, 64, 65)
  const goodSums = [40, 41, 42, 44, 45, 49, 50, 51, 54, 55, 56, 59, 60, 63, 64, 65];
  if (goodSums.includes(sum)) {
    score += 15;
  }

  score = Math.max(10, Math.min(100, score));

  return {
    rawNumber: raw,
    formattedNumber: formatted,
    provider,
    totalSum: sum,
    totalScore: score,
    pairScore: Math.min(100, auspiciousFound.length * 15),
    sumScore: goodSums.includes(sum) ? 95 : 60,
    isTopCandidate: score >= 88 && dangerousFound.length === 0,
    dangerousPairs: dangerousFound,
    auspiciousPairs: auspiciousFound,
    energyProfile: {
      wealth: Math.min(99, 40 + auspiciousFound.length * 10),
      charm: Math.min(99, 45 + (pairs.includes("24") || pairs.includes("42") || pairs.includes("23") || pairs.includes("32") || pairs.includes("65") || pairs.includes("56") ? 35 : 0)),
      prestige: Math.min(99, 40 + (pairs.includes("78") || pairs.includes("87") || pairs.includes("89") || pairs.includes("98") || pairs.includes("15") || pairs.includes("51") ? 40 : 0)),
      wisdom: Math.min(99, 50 + (pairs.includes("45") || pairs.includes("54") || pairs.includes("59") || pairs.includes("95") || pairs.includes("55") ? 35 : 0)),
      luck: Math.min(99, 45 + (pairs.includes("63") || pairs.includes("36") || pairs.includes("99") || pairs.includes("89") || pairs.includes("98") ? 35 : 0)),
    },
  };
}

