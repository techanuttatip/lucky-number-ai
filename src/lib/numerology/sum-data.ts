export function getSumRule(sum: number): SumRule {
  if (SUM_RULES_MAP[sum]) {
    return SUM_RULES_MAP[sum];
  }

  // Fallback rating
  const goodSums = [36, 40, 41, 42, 44, 45, 46, 49, 50, 51, 54, 55, 56, 59, 63, 64, 65, 68, 79];
  const isGood = goodSums.includes(sum);

  return {
    sum,
    tier: isGood ? "A" : "C",
    title: `ผลรวม ${sum}`,
    meaning: isGood ? "ผลรวมมงคลระดับมาตรฐาน ให้คุณประโยชน์ทั่วไป" : "ผลรวมระดับปานกลาง",
    isAuspicious: isGood,
  };
}
